export const QUESTIONS: Question[] = (Object.keys(BANK) as CategoryId[]).flatMap((category) =>
  BANK[category].map(([text, answer], index) => ({
    id: `${category}-${index + 1}`,
    category,
    text,
    answer,
  })),
);

const BY_ID = new Map(QUESTIONS.map((question) => [question.id, question]));

export function getQuestion(id: string): Question {
  const question = BY_ID.get(id);
  if (!question) throw new Error(`Pergunta desconhecida: ${id}`);
  return question;
}
